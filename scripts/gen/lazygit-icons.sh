#!/bin/bash

set -euo pipefail

DOTFILES="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
OUT="$DOTFILES/.config/lazygit/icons.yml"
SRC="https://raw.githubusercontent.com/jesseduffield/lazygit/master/pkg/gui/presentation/icons/file_icons.go"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

command -v nvim >/dev/null || { echo "nvim not found" >&2; exit 1; }
command -v python3 >/dev/null || { echo "python3 not found" >&2; exit 1; }

curl -fsSL "$SRC" -o "$TMP/file_icons.go" || { echo "failed to fetch $SRC" >&2; exit 1; }

python3 - "$TMP/file_icons.go" "$TMP/targets.json" <<'PY'
import json, re, sys

src, dst = sys.argv[1], sys.argv[2]
lines = open(src).read().split("\n")
names, exts = [], []
cur = None
for line in lines:
    if line.startswith("var nameIconMap"):
        cur = names
    elif line.startswith("var extIconMap"):
        cur = exts
    elif line.startswith("}"):
        cur = None
    elif cur is not None:
        m = re.match(r'\s*"([^"]+)":', line)
        if m:
            cur.append(m.group(1))
json.dump({"names": names, "exts": exts}, open(dst, "w"))
PY

nvim --headless -c "lua
local dv = require('nvim-web-devicons')
local lg = vim.json.decode(table.concat(vim.fn.readfile('$TMP/targets.json'), ''))

local function resolve(name)
  local icon, hl = dv.get_icon(name)
  if not icon then return nil end
  local h = vim.api.nvim_get_hl(0, { name = hl or '', link = false })
  return { icon, h.fg and string.format('#%06x', h.fg) or '' }
end

local out = { exts = {}, files = {} }
-- lazygit は filepath.Ext で最後の拡張子しか見ないため複合拡張子は写せない
for ext in pairs(dv.get_icons_by_extension()) do
  if not ext:find('%.') then out.exts[ext] = resolve('x.' .. ext) end
end
for name in pairs(dv.get_icons_by_filename()) do out.files[name] = resolve(name) end
for _, ext in ipairs(lg.exts) do
  ext = ext:gsub('^%.', '')
  if not ext:find('%.') then out.exts[ext] = out.exts[ext] or resolve('x.' .. ext) or vim.NIL end
end
for _, name in ipairs(lg.names) do out.files[name] = out.files[name] or resolve(name) or vim.NIL end

vim.fn.writefile({ vim.json.encode(out) }, '$TMP/icons.json')
" -c 'qa'

python3 - "$TMP/icons.json" "$OUT" <<'PY'
import json, sys

src, dst = sys.argv[1], sys.argv[2]
d = json.load(open(src))

FALLBACK = ["\uf15b", "#878787"]


ENV_VARIANTS = [
    ".env.local", ".env.sample", ".env.example", ".env.test",
    ".env.development", ".env.production", ".envrc",
]

def norm(m):
    return {k: (v if isinstance(v, list) else FALLBACK) for k, v in m.items()}

files, exts = norm(d["files"]), norm(d["exts"])

for key in list(files):
    stem, dot, ext = key.partition(".")
    if not stem:
        continue
    for cased in (stem.capitalize(), stem.upper()):
        files.setdefault(cased + dot + ext, files[key])

if ".env" in files:
    for name in ENV_VARIANTS:
        files[name] = files[".env"]

out = [
    "# Generated by scripts/gen/lazygit-icons.sh -- DO NOT EDIT",
    "#",
    "# nvim-web-devicons と同じアイコンを lazygit にも出させる",
    "# yazi は同じセットを内蔵しているので、これで 3 つが揃う",
    "",
    "gui:",
    "  customIcons:",
    "    filenames:",
]
for k in sorted(files):
    icon, color = files[k]
    out.append(f'      "{k}": {{ icon: "{icon}", color: "{color}" }}')
out.append("    extensions:")
for k in sorted(exts):
    icon, color = exts[k]
    out.append(f'      ".{k}": {{ icon: "{icon}", color: "{color}" }}')
out.append("")

open(dst, "w", encoding="utf-8").write("\n".join(out))
print(f"filenames={len(files)} extensions={len(exts)} -> {dst}")
PY
